-- Fail during stock UPDATE, after receipt/items INSERT, to prove full rollback.
CREATE FUNCTION cssm_sale_regression.fail_stock_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Injected write failure'; END;
$$;
CREATE TRIGGER fail_stock BEFORE UPDATE ON cssm_sale_regression.products
 FOR EACH ROW EXECUTE FUNCTION cssm_sale_regression.fail_stock_update();
DO $test$
DECLARE v_count integer; v_items integer; v_stock integer;
BEGIN
 SELECT count(*) INTO v_count FROM cssm_sale_regression.transactions;
 SELECT count(*) INTO v_items FROM cssm_sale_regression.transaction_items;
 SELECT stock INTO v_stock FROM cssm_sale_regression.products WHERE id=1;
 BEGIN
  PERFORM cssm_sale_regression.create_sale_atomic('rollback',1,1,'cash',10,10,'[{"product_id":1,"quantity":1}]');
  RAISE EXCEPTION 'Failure injection did not run';
 EXCEPTION WHEN raise_exception THEN
  IF SQLERRM <> 'Injected write failure' THEN RAISE; END IF;
 END;
 IF (SELECT count(*) FROM cssm_sale_regression.transactions) <> v_count
 OR (SELECT count(*) FROM cssm_sale_regression.transaction_items) <> v_items
 OR (SELECT stock FROM cssm_sale_regression.products WHERE id=1) <> v_stock
 THEN RAISE EXCEPTION 'Failed sale was not fully rolled back'; END IF;
END;
$test$;
ROLLBACK;
