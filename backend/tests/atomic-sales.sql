 staff_id integer REFERENCES cssm_sale_regression.staff(id), total_amount numeric(10,2),
 payment_method text, tendered_amount numeric(10,2), change_amount numeric(10,2)
);
CREATE TABLE cssm_sale_regression.transaction_items (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transaction_id integer REFERENCES cssm_sale_regression.transactions(id),
 product_id integer REFERENCES cssm_sale_regression.products(id), quantity integer,
 unit_price numeric(10,2), subtotal numeric(10,2)
);
