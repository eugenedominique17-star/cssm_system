CREATE TABLE cssm_sale_regression.staff (id integer PRIMARY KEY, status text NOT NULL);
CREATE TABLE cssm_sale_regression.clients (id integer PRIMARY KEY, status text NOT NULL);
CREATE TABLE cssm_sale_regression.products (
 id integer PRIMARY KEY, name text NOT NULL, status text NOT NULL, stock integer NOT NULL,
 price numeric(10,2) NOT NULL, expiry_date date
